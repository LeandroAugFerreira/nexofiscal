const {chromium}=require(process.env.FITNOTA_PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs');
const output=path.join(__dirname,'..','artifacts','screenshots');
fs.mkdirSync(output,{recursive:true});
let browser;
(async()=>{
  browser=await chromium.launch({headless:true,channel:'msedge'});
  const page=await browser.newPage({viewport:{width:1600,height:1000},locale:'pt-BR'});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:5180');
  await page.getByRole('heading',{name:'Conheça o projeto',exact:true}).waitFor();
  assert(await page.getByText('portfolio@nexofiscal.example.com',{exact:true}).isVisible());
  assert(await page.getByText('NexoFiscalDemo@2026',{exact:true}).isVisible());
  await page.screenshot({path:path.join(output,'login-portfolio.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.screenshot({path:path.join(output,'login-portfolio-mobile.png'),fullPage:true});
  await page.getByRole('button',{name:'Entrar no portfólio',exact:true}).click();
  await page.getByRole('heading',{name:'Central de emissão',exact:true}).waitFor();
  const me=await page.request.get('http://127.0.0.1:5180/api/auth/me');
  assert.equal((await me.json()).role,'portfolio');
  await page.getByRole('button',{name:'Sair',exact:true}).click();
  await page.getByRole('heading',{name:'Vamos começar?',exact:true}).waitFor();
  assert.deepEqual(errors,[]);
  console.log('Portfólio PASS: credenciais visíveis, login com conta dedicada, logout e layout móvel sem overflow.');
})().finally(async()=>{if(browser)await browser.close();}).catch(e=>{console.error(e);process.exitCode=1;});
