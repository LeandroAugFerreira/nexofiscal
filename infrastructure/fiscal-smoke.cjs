const {chromium}=require(process.env.FITNOTA_PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const output=path.join(__dirname,'..','artifacts','screenshots');
fs.mkdirSync(output,{recursive:true});
let browser;
(async()=>{
  browser=await chromium.launch({headless:true,channel:'msedge'});
  const page=await browser.newPage({viewport:{width:1600,height:1000},locale:'pt-BR'});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const base='http://127.0.0.1:5180';
  await page.goto(base);
  await page.getByRole('button',{name:'Entrar no portfólio',exact:true}).click();
  await page.getByRole('heading',{name:'Central de emissão',exact:true}).waitFor();
  await page.getByText('Notas e solicitações recentes',{exact:true}).waitFor();
  await page.locator('main .state:has(.spin)').waitFor({state:'hidden'});
  await page.screenshot({path:path.join(output,'central-emissao.png'),fullPage:true});
  const before=(await (await page.request.get(base+'/api/dashboard')).json());
  await page.locator('main').getByRole('link',{name:'Emitir NFS-e',exact:true}).click();
  await page.getByRole('heading',{name:'Para quem você está emitindo?',exact:true}).waitFor();
  const clientValue=await page.getByRole('option',{name:/Empresa Beta/}).getAttribute('value');
  await page.getByLabel('Cliente / tomador',{exact:true}).selectOption(clientValue);
  await page.getByRole('button',{name:'Continuar',exact:true}).click();
  await page.getByRole('heading',{name:'Qual serviço será documentado?',exact:true}).waitFor();
  const serviceValue=await page.getByRole('option',{name:/^Consultoria/}).getAttribute('value');
  await page.getByLabel('Serviço',{exact:true}).selectOption(serviceValue);
  await page.getByLabel('Valor do serviço (R$)',{exact:true}).fill('275.50');
  await page.getByLabel('Descrição do serviço na nota',{exact:true}).fill('Consultoria de processos • Teste de emissão genérica');
  await page.getByRole('button',{name:'Revisar dados',exact:true}).click();
  await page.getByRole('heading',{name:'Revise antes de emitir',exact:true}).waitFor();
  await page.screenshot({path:path.join(output,'revisao-nfse-pj.png'),fullPage:true});
  await page.getByRole('button',{name:'Emitir NFS-e simulada',exact:true}).click();
  await page.getByRole('heading',{name:'Documento simulado gerado',exact:true}).waitFor();
  const result=page.getByRole('link',{name:'Abrir documento simulado',exact:true});
  const documentUrl=await result.getAttribute('href');
  const response=await page.request.get(base+documentUrl);
  assert.equal(response.status(),200);
  const content=await response.text();
  assert(content.includes('SEM VALIDADE FISCAL')&&content.includes('Empresa Beta'));
  const after=await (await page.request.get(base+'/api/dashboard')).json();
  assert.equal(after.received,before.received,'Emissão avulsa não pode gerar pagamento');
  assert.equal(after.expected,before.expected,'Emissão avulsa não pode gerar cobrança');
  await page.getByRole('link',{name:'Ver histórico fiscal',exact:true}).click();
  await page.getByRole('heading',{name:'Histórico fiscal',exact:true}).waitFor();
  await page.getByRole('button',{name:'Solicitar cancelamento',exact:true}).click();
  await page.getByLabel('Motivo do cancelamento').fill('Cancelamento demonstrativo após verificação do fluxo de NFS-e');
  await page.getByRole('button',{name:'Confirmar cancelamento',exact:true}).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  await page.getByText('Cancelada',{exact:true}).first().waitFor();
  await page.goto(base+'/emitir');
  await page.getByRole('heading',{name:'Para quem você está emitindo?',exact:true}).waitFor();
  const pf=await page.getByRole('option',{name:/Ana Oliveira/}).getAttribute('value');
  await page.getByLabel('Cliente / tomador',{exact:true}).selectOption(pf);
  await page.getByRole('button',{name:'Continuar',exact:true}).click();
  await page.getByLabel('Serviço',{exact:true}).selectOption(serviceValue);
  await page.getByRole('button',{name:'Revisar dados',exact:true}).click();
  await page.getByLabel('Simular rejeição para testar o tratamento de erros',{exact:true}).check();
  await page.getByRole('button',{name:'Emitir NFS-e simulada',exact:true}).click();
  await page.getByRole('heading',{name:'A simulação foi rejeitada',exact:true}).waitFor();
  await page.getByRole('link',{name:'Ver histórico fiscal',exact:true}).click();
  await page.getByRole('button',{name:'Reprocessar simulação',exact:true}).click();
  await page.getByRole('link',{name:'Abrir documento',exact:true}).waitFor();
  await page.goto(base+'/clients');
  await page.getByRole('button',{name:'Novo cliente',exact:true}).click();
  await page.getByLabel('Tipo de pessoa').selectOption('pj');
  assert(await page.getByLabel('CNPJ',{exact:false}).isVisible());
  assert.equal(await page.getByLabel('CPF',{exact:false}).count(),0);
  await page.getByRole('button',{name:'Fechar janela',exact:true}).click();
  for(const [value,name] of [['light','Light'],['fitness','Contraste'],['dark','Dark']]){
    await page.getByRole('button',{name:`Tema ${name}`,exact:true}).click();
    assert.equal(await page.locator('html').getAttribute('data-theme'),value);
  }
  for(const [route,title] of [['/company','Empresa emissora'],['/fiscal-config','Configuração fiscal'],['/financeiro','Visão financeira'],['/charges','Cobranças']]){
    await page.goto(base+route);await page.getByRole('heading',{name:title,exact:true}).waitFor();
    await page.locator('main .state:has(.spin)').waitFor({state:'hidden'});
    assert.equal(await page.locator('main .state.error').count(),0,route);
  }
  await page.setViewportSize({width:390,height:844});
  await page.goto(base);await page.getByRole('heading',{name:'Central de emissão',exact:true}).waitFor();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Central móvel com overflow');
  await page.screenshot({path:path.join(output,'central-emissao-mobile.png'),fullPage:true});
  await page.goto(base+'/emitir');await page.getByRole('heading',{name:'Para quem você está emitindo?',exact:true}).waitFor();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Emissão móvel com overflow');
  await page.getByRole('button',{name:'Sair',exact:true}).click();
  await page.getByRole('heading',{name:'Vamos começar?',exact:true}).waitFor();
  assert.deepEqual(errors,[]);
  console.log('Fiscal UI PASS: central inicial, emissão PJ, documento, cancelamento, emissão PF rejeitada/reprocessada, cadastro PF/PJ, financeiro preservado, temas, mobile e logout.');
})().finally(async()=>{if(browser)await browser.close();}).catch(e=>{console.error(e);process.exitCode=1;});
