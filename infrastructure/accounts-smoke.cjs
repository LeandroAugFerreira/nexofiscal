// Executar com accounts-preview-server.py: somente dados fictícios, nenhum envio.
const {chromium}=require(process.env.FITNOTA_PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict'),path=require('node:path'),fs=require('node:fs');
const base='http://127.0.0.1:5180',backend='http://127.0.0.1:8011';
const shots=path.resolve(__dirname,'../artifacts/screenshots/accounts');fs.mkdirSync(shots,{recursive:true});
let browser,stage='startup';
(async()=>{
  browser=await chromium.launch({headless:true,channel:'msedge'});
  const context=await browser.newContext({viewport:{width:1440,height:1000},locale:'pt-BR'});
  const page=await context.newPage(),errors=[],blocked=[];
  page.on('pageerror',e=>errors.push(e.name));
  await page.route('**/api/**',route=>{
    const r=route.request(),url=new URL(r.url());
    if(!['GET','HEAD'].includes(r.method())&&!/^\/api\/(auth\/(login|logout|me|password)|users(\/\d+)?)$/.test(url.pathname)){
      blocked.push(url.pathname);return route.abort();
    }
    return route.continue({url:backend+url.pathname+url.search});
  });
  const shot=async name=>{await page.evaluate(()=>document.fonts.ready);await page.screenshot({path:path.join(shots,name+'.png'),fullPage:true});};
  const login=async(email,password,route='/users',heading='Usuários')=>{await page.goto(base+route);await page.getByLabel('E-mail',{exact:true}).fill(email);await page.getByLabel('Senha',{exact:true}).fill(password);await page.getByRole('button',{name:'Entrar no NexoFiscal',exact:true}).click();await page.getByRole('heading',{name:heading,exact:true}).waitFor();};
  const current='Accounts-QA-admin-123',password='Accounts-QA-created-123';
  stage='create';await login('admin@example.com',current);
  await page.getByRole('button',{name:'Novo usuário',exact:true}).click();
  await page.getByLabel('Nome completo',{exact:true}).fill('Pessoa Fictícia QA');
  await page.getByLabel('E-mail de acesso',{exact:true}).fill('pessoa@example.com');
  await page.getByLabel('Perfil de acesso',{exact:true}).selectOption('financeiro');
  await page.getByLabel('Senha inicial',{exact:true}).fill(password);
  await page.getByLabel('Confirmar senha',{exact:true}).fill('Different-QA-password');
  await page.getByRole('button',{name:'Salvar usuário',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'A confirmação da senha não confere.'}).waitFor();
  await page.getByLabel('Confirmar senha',{exact:true}).fill(password);await shot('novo-usuario');
  await page.getByRole('button',{name:'Salvar usuário',exact:true}).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  await page.getByRole('row').filter({hasText:'pessoa@example.com'}).waitFor();await shot('usuarios');
  stage='edit';await page.getByRole('button',{name:'Editar Pessoa Fictícia QA',exact:true}).click();
  await page.getByLabel('Status da conta',{exact:true}).selectOption('false');
  await page.getByRole('button',{name:'Salvar alterações',exact:true}).click();await page.getByRole('dialog').waitFor({state:'hidden'});
  await page.getByRole('row').filter({hasText:'Pessoa Fictícia QA'}).getByText('Inativo',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Editar Pessoa Fictícia QA',exact:true}).click();
  await page.getByLabel('Status da conta',{exact:true}).selectOption('true');
  await page.getByRole('button',{name:'Salvar alterações',exact:true}).click();await page.getByRole('dialog').waitFor({state:'hidden'});
  stage='profile';await page.getByRole('link',{name:'Minha conta',exact:true}).first().click();
  await page.getByRole('heading',{name:'Minha conta',exact:true}).waitFor();
  await page.getByLabel('Nome completo',{exact:true}).fill('Administrador Atualizado QA');
  await page.getByLabel('Senha atual',{exact:true}).fill(current);
  await page.getByRole('button',{name:'Salvar dados',exact:true}).click();
  await page.locator('.topbar .user').getByText('Administrador Atualizado QA',{exact:true}).waitFor();await shot('minha-conta');
  await page.getByRole('tab',{name:'Segurança',exact:true}).click();
  await page.getByLabel('Senha atual',{exact:true}).fill(current);
  const replacement='Accounts-QA-updated-123';
  await page.getByLabel('Nova senha',{exact:true}).fill(replacement);await page.getByLabel('Confirmar nova senha',{exact:true}).fill(replacement);
  await page.getByRole('button',{name:'Salvar nova senha',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Senha alterada.'}).waitFor();await shot('seguranca');
  await page.setViewportSize({width:390,height:844});
  assert(await page.getByRole('link',{name:'Minha conta',exact:true}).first().isVisible());await shot('conta-mobile');
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.getByRole('button',{name:'Sair',exact:true}).click();
  stage='new-login';await login('pessoa@example.com',password,'/account','Minha conta');
  await page.goto(base+'/users');await page.getByText('Seu perfil não permite acessar esta página.',{exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Novo usuário',exact:true}).count(),0);
  await page.goto(base+'/account');await page.getByRole('heading',{name:'Minha conta',exact:true}).waitFor();
  await page.getByRole('heading',{name:'Financeiro',exact:true}).waitFor();
  await page.getByRole('button',{name:'Sair',exact:true}).click();
  stage='portfolio';await page.getByRole('button',{name:'Entrar no portfólio',exact:true}).click();
  await page.getByRole('heading',{name:'Conta pública de demonstração',exact:true}).waitFor();
  await page.goto(base+'/users');await page.getByRole('heading',{name:'Usuários',exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Novo usuário',exact:true}).count(),0);
  await page.goto(base+'/account');await page.getByRole('heading',{name:'Conta pública de demonstração',exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Salvar dados',exact:true}).count(),0);
  assert.equal(errors.length,0);assert.equal(blocked.length,0);
  console.log('PASS: criação, confirmação, edição, acesso por perfil, minha conta, senha, mobile e conta pública. Nenhum e-mail ou nota emitidos.');
})().catch(async error=>{console.error('FAIL stage='+stage+' '+error.message);process.exitCode=1;}).finally(async()=>{await browser?.close();});
